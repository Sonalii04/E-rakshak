export const translations = { en, hi, mr, bn, ta, te }

export function translateStatic(key) {
  const lang = typeof localStorage !== 'undefined' ? localStorage.getItem('sentryvision_language') || 'en' : 'en'
  const lookup = (dict) => key.split('.').reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), dict)
  return lookup(translations[lang]) ?? lookup(translations.en) ?? key
}
